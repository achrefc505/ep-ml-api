def lookup_market_price_per_sqm(postal_code: str | None) -> float:
    """Retourne le prix marché €/m² estimé pour ce CP.
    Fallback : centroïde département → médian France.
    """
    if not postal_code:
        return DEFAULT_PRICE_PER_SQM
    pc = str(postal_code).strip().zfill(5)[:5]
    if pc in _PARIS:
        return _PARIS[pc]
    if pc in _LYON:
        return _LYON[pc]
    if pc in _MARSEILLE:
        return _MARSEILLE[pc]
    if pc in _OTHERS:
        return _OTHERS[pc]
    dept = pc[:2]
    return _DEPT.get(dept, DEFAULT_PRICE_PER_SQM)
