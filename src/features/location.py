def lookup_latlng(postal_code: str | None) -> tuple[float, float] | None:
    """Retourne (lat, lng) plausible pour un code postal français.
    None si introuvable.
    """
    if not postal_code:
        return None
    pc = str(postal_code).strip().zfill(5)[:5]
    if pc in _PARIS:
        return _PARIS[pc]
    if pc in _LYON:
        return _LYON[pc]
    if pc in _MARSEILLE:
        return _MARSEILLE[pc]
    return _DEPT_CENTROIDS.get(pc[:2])
